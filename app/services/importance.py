# -- Предфильтр --------------------------------------------------------------

# Предмет акта — текст названия в кавычках после «№ …». Шаблоны проверяются от начала
# предмета без учёта регистра (кроме ФИО — см. _PERSONAL_NAME_RE).
_SUBJECT_RE = re.compile(r'№\s*[^"«\s]+\s*["«](.+)', re.DOTALL)

# Персональный кадровый указ: «О Фамилии И.О.» / «Об Фамилии И.О.» (весь предмет)
_PERSONAL_NAME_RE = re.compile(r"^(?:О|Об)\s+[А-ЯЁ][а-яё\-]+\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.[\s\"»]*$")

# Шаблоны заведомо рутинных актов (design.md, п. 5). Намеренно НЕ входят:
# «О назначении выборов», ратификации, «О внесении изменения в Указ … № 95»,
# «О внесении изменений в некоторые акты Правительства» — их решает модель.
_PREFILTER_PATTERNS: dict[str, tuple[re.Pattern[str], ...]] = {
    "DECREE": tuple(
        re.compile(p, re.IGNORECASE)
        for p in (
            r"О Чрезвычайном и Полномочном Посл",
            r"О присвоении",
            r"О награждении",
            r"О внесении изменени[йя] в состав",
            r"О праздновании",
            r"О (?:заместителе|руководителе|советнике|генеральном директоре|атамане|председателе)\b",
            r"О присуждении",
            r"О назначении (?:на должность|судей)",
            r"О Полномочном представителе",
            r"Об исполняющ(?:ем|ей) обязанности",
            r"Об освобождении",
            r"О восстановлении в правах на государственн",
            r"О приеме в гражданство",
            r"Об увековечении памяти",
            r"О Дне ",
        )
    ),
    "GOV_RESOLUTION": tuple(
        re.compile(p, re.IGNORECASE)
        for p in (
            r"Об авансировании государственн",
            r"Об изменении существенных условий (?:государственных )?контрактов",
        )
    ),
}


def _subject(title: str) -> str:
    """Предмет акта: текст названия после ``№ … "``; весь заголовок, если не найден."""
    match = _SUBJECT_RE.search(title)
    return (match.group(1) if match else title).strip()


def prefilter_zero(level: str, title: str) -> bool:
    """
    True, если акт заведомо рутинный по заголовку и ему сразу ставится ``0``.

    Применяется только к ``DECREE`` и ``GOV_RESOLUTION``; для остальных уровней всегда False.
    """
    patterns = _PREFILTER_PATTERNS.get(level)
    if not patterns:
        return False
    subject = _subject(title)
    if level == "DECREE" and _PERSONAL_NAME_RE.match(subject):
        return True
    return any(p.match(subject) for p in patterns)


