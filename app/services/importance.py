"""
Оценка важности нормативного акта для еженедельной подборки.

Две ступени:

1. ``prefilter_zero`` — предфильтр по заголовку: заведомо рутинные указы и
   постановления (награждения, послы, кадровые указы и т.п.) сразу получают ``0``
   без вызова LLM.
2. ``score_importance`` — GigaChat оценивает акт по рубрике от 0 до 3 отдельным
   запросом (не совмещённым с суммаризацией).

Оценка внутренняя, пользователю не показывается. Результат ``None`` значит
«не оценено» (сбой, невалидный ответ) — вызывающий код повторит оценку позже.

Промпты и шаблоны — константы модуля (prompt management, vision.md).
"""

