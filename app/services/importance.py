_USER_PROMPT_TEMPLATE = "Акт: {title}\n{body}\nОцени важность акта."
_TITLE_ONLY_USER_PROMPT_TEMPLATE = "Акт: {title}\nОцени важность акта по названию."


def _few_shot_messages() -> list[dict[str, str]]:
    """Примеры как пары реплик «акт → JSON-ответ» (так модель надёжнее держит формат)."""
    messages: list[dict[str, str]] = []
    for _, title, summary, reason, level in _FEW_SHOT:
        body = f"Краткое содержание: {summary}" if summary else None
        if body:
            user = _USER_PROMPT_TEMPLATE.format(title=title, body=body)
        else:
            user = _TITLE_ONLY_USER_PROMPT_TEMPLATE.format(title=title)
        answer = json.dumps({"reason": reason, "level": level}, ensure_ascii=False)
        messages += [{"role": "user", "content": user}, {"role": "assistant", "content": answer}]
    return messages


_FEW_SHOT_MESSAGES = _few_shot_messages()

# Если JSON сломан (например, неэкранированные кавычки в reason), достаём метку напрямую
_LEVEL_RE = re.compile(r'"level"\s*:\s*"?([0-3])\b')


def build_body(summary: str | None, text: str | None) -> str | None:
    """
    Вход оценки помимо названия: саммари, иначе начало текста, иначе None.

    None означает «только название»: на приёме это повод отложить оценку (текст часто
    появляется позже), оценка по одному названию допустима лишь на финальном проходе
    или после неудачного OCR.
    """
    if summary and summary.strip():
        return f"Краткое содержание: {summary.strip()[:_MAX_BODY_CHARS]}"
    if text and text.strip():
        return f"Начало текста: {text.strip()[:_MAX_BODY_CHARS]}"
    return None


def _parse_level(reply: str) -> int | None:
    """Достаёт уровень 0–3 из ответа модели; None, если ответ не по формату."""
    match = re.search(r"\{.*\}", reply, re.DOTALL)
    if match:
        try:
            data = json.loads(match.group(0))
            level = data.get("level") if isinstance(data, dict) else None
            if isinstance(level, int) and not isinstance(level, bool) and 0 <= level <= 3:
                return level
        except ValueError:
            pass
    fallback = _LEVEL_RE.search(reply)
    return int(fallback.group(1)) if fallback else None


async def _ask(client: GigaChatClient, title: str, body: str | None) -> int | None:
    """
    Один запрос оценки (с одним повтором при невалидном ответе).

    Returns:
        Уровень 0–3, ``-1`` при отказе модели, ``None`` при невалидном ответе.
    Raises:
        GigaChatError: сбой сети/API (временная ошибка).
    """
    if body:
        user_prompt = _USER_PROMPT_TEMPLATE.format(title=title, body=body)
    else:
        user_prompt = _TITLE_ONLY_USER_PROMPT_TEMPLATE.format(title=title)
    messages = [
        {"role": "system", "content": _SYSTEM_PROMPT},
        *_FEW_SHOT_MESSAGES,
        {"role": "user", "content": user_prompt},
    ]
    for attempt in (1, 2):
        reply = await client.complete(
            messages, temperature=_TEMPERATURE, max_tokens=_MAX_OUTPUT_TOKENS
        )
        # Сначала разбор: валидный JSON — не отказ, даже если в reason есть слова вроде
        # «ограничивает» (classify_reply на коротких ответах реагирует на такие маркеры).
        level = _parse_level(reply)
        if level is not None:
            return level
        if classify_reply(reply) == "refusal":
            return -1
        logger.warning("Оценка важности: невалидный ответ (попытка %d): %r", attempt, reply[:200])
    return None


async def score_importance(client: GigaChatClient, title: str, body: str | None) -> int | None:
    """
    Оценивает важность акта: 0 — не важно, 1 — нейтрально, 2 — важно, 3 — критически важно.

    Args:
        client: клиент GigaChat.
        title: полный заголовок акта.
        body: саммари/начало текста (см. ``build_body``) или None — оценка по одному названию.

    Returns:
        Оценка 0–3. ``None`` — не оценено (временный сбой или невалидный ответ), оценку
        нужно повторить позже. Отказ модели: повторная оценка по одному названию, при
        повторном отказе — ``REFUSAL_FALLBACK_SCORE`` (чувствительная тема не должна
        выпадать из подборки).
    """
    try:
        result = await _ask(client, title, body)
        if result == -1 and body:
            logger.info("Оценка важности: отказ модели, повторяем по одному названию: %s", title[:150])
            result = await _ask(client, title, None)
    except GigaChatError as exc:
        logger.warning("Оценка важности не удалась (%s): %s", exc, title[:150])
        return None
    if result == -1:
        logger.warning(
            "Оценка важности: отказ модели и по названию — ставим %d: %s",
            REFUSAL_FALLBACK_SCORE, title[:150],
        )
        return REFUSAL_FALLBACK_SCORE
    return result
